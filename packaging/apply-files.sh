#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# W2/W3/W4 — Apply staged files (LICENSE, README, CI) to each repository.
#
# For every repo it:
#   1. clones into a temp dir (shallow, default branch)
#   2. creates branch  chore/packaging
#   3. copies the staged files from ./files/<repo>/
#   4. commits with a conventional message
#   5. pushes the branch and opens a pull request
#
# Nothing lands on main. Every change is reviewable as a PR before merge.
#
# Usage:
#   ./apply-files.sh --dry-run          # show what would change, touch nothing
#   ./apply-files.sh                    # all repos
#   ./apply-files.sh Arbor Preen        # only these
#   ./apply-files.sh --no-pr            # push branch, do not open a PR
# ---------------------------------------------------------------------------
set -uo pipefail

OWNER="mdadeel"
BRANCH="chore/packaging"
STAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FILES_DIR="$STAGE_DIR/files"
WORK_DIR="${TMPDIR:-/tmp}/packaging-apply"
DRY_RUN=0
OPEN_PR=1
REPOS=()

for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    --no-pr)   OPEN_PR=0 ;;
    -*) echo "unknown flag: $arg"; exit 2 ;;
    *) REPOS+=("$arg") ;;
  esac
done

if [ "${#REPOS[@]}" -eq 0 ]; then
  # Every directory under files/ that has content.
  while IFS= read -r d; do REPOS+=("$(basename "$d")"); done < <(find "$FILES_DIR" -mindepth 1 -maxdepth 1 -type d | sort)
fi

mkdir -p "$WORK_DIR"
FAILED=0; DONE=0; SKIPPED=0

for repo in "${REPOS[@]}"; do
  src="$FILES_DIR/$repo"
  echo
  echo "=== $repo ==============================================="

  if [ ! -d "$src" ]; then
    echo "  SKIP  no staged files for $repo"
    SKIPPED=$((SKIPPED + 1)); continue
  fi

  # Confirm we can actually read the repo (the backend repo is private).
  if ! gh api "repos/$OWNER/$repo" --jq '.name' >/dev/null 2>&1; then
    echo "  SKIP  not accessible with the current token (private repo, no access)"
    SKIPPED=$((SKIPPED + 1)); continue
  fi

  work="$WORK_DIR/$repo"
  rm -rf "$work"

  if ! git clone -q "https://github.com/$OWNER/$repo.git" "$work" 2>/dev/null; then
    echo "  FAIL  clone failed"
    FAILED=$((FAILED + 1)); continue
  fi

  # Show the plan, file by file.
  changed=0
  while IFS= read -r rel; do
    rel="${rel#"$src"/}"
    target="$work/$rel"
    if [ -f "$target" ] && cmp -s "$src/$rel" "$target"; then
      echo "  same  $rel"
    elif [ -f "$target" ]; then
      echo "  update $rel   (+$(wc -l <"$src/$rel" | tr -d ' ') lines staged, was $(wc -l <"$target" | tr -d ' '))"
      changed=$((changed + 1))
    else
      echo "  add    $rel"
      changed=$((changed + 1))
    fi
  done < <(cd "$src" && find . -type f | sed 's|^\./||' | sort)

  if [ "$changed" -eq 0 ]; then
    echo "  -- nothing to change"
    rm -rf "$work"; continue
  fi

  if [ "$DRY_RUN" -eq 1 ]; then
    echo "  [dry run] would commit $changed file(s) to branch $BRANCH"
    rm -rf "$work"; DONE=$((DONE + 1)); continue
  fi

  (
    cd "$work" || exit 1
    git checkout -q -B "$BRANCH"
    config_files=(); readme=0; ci=0; license=0
    while IFS= read -r rel; do
      mkdir -p "$(dirname "$rel")"
      cp "$src/$rel" "$rel"
      case "$rel" in
        .github/workflows/*) ci=1 ;;
        README.md)           readme=1 ;;
        LICENSE)             license=1 ;;
      esac
    done < <(cd "$src" && find . -type f | sed 's|^\./||' | sort)

    msg="chore: packaging — project metadata, licensing and CI

- Add LICENSE so the repository has explicit terms
- Rewrite README with real setup steps, architecture and an honest status section"

    [ "$ci" -eq 1 ] && msg="$msg
- Add GitHub Actions CI (no badge until it is green)"
    [ "$license" -eq 1 ] && msg="$msg
- Set licence terms in LICENSE"

    git add -A
    git -c user.name="Shahnawas Adeel" -c user.email="shahnawasadeel@gmail.com" \
      commit -q -m "$msg"
    git push -q -u origin "$BRANCH" --force-with-lease
  ) || { echo "  FAIL  commit/push failed"; FAILED=$((FAILED + 1)); rm -rf "$work"; continue; }

  if [ "$OPEN_PR" -eq 1 ]; then
    if gh pr view "$BRANCH" --repo "$OWNER/$repo" >/dev/null 2>&1; then
      echo "  PR already open for $BRANCH — branch updated"
    else
      gh pr create --repo "$OWNER/$repo" \
        --base "$(gh api "repos/$OWNER/$repo" --jq '.default_branch')" \
        --head "$BRANCH" \
        --title "Packaging: licence, README and CI" \
        --body "Adds explicit licensing, a README rewritten from the actual code, and CI.

**Review before merging:**
- [ ] \`LICENSE\` terms are the ones you want for this repo
- [ ] Any \`TODO (owner)\` markers in the README are resolved
- [ ] Screenshots added (see the placeholder block near the top)
- [ ] CI runs green — only then enable the commented badge in the README

Generated by the packaging plan (\`REPO-PACKAGING-PLAN.md\`)." >/dev/null 2>&1 \
        && echo "  OK    branch pushed + PR opened" \
        || echo "  WARN  branch pushed, but PR creation failed (open it manually)"
    fi
  else
    echo "  OK    branch $BRANCH pushed"
  fi

  DONE=$((DONE + 1))
  rm -rf "$work"
done

echo
echo "======================================================"
echo "repos updated: $DONE   skipped: $SKIPPED   failed: $FAILED"
[ "$DRY_RUN" -eq 1 ] && echo "(dry run — nothing was changed)"
exit 0
